local function normalized(s)return (s or ''):lower():gsub('[^a-z0-9]','')end
function M.apply(data,character)
    local source=rows[character];if not source then return data end
    local identities={}
    for _,d in ipairs(data.cards.cards)do
        for _,s in ipairs({d.id,d.sourceId or '',d.sts_name or ''})do if s~=''then identities[normalized(s)]=d.id end end
    end
    local pools=data.cards.sourcePools or {}
    local reward,src,shop,metadata={},{},{},{}
    for _,rarity in ipairs({'common','uncommon','rare'})do
        reward[rarity]={};src[rarity]={};shop[rarity]={attack={},skill={},power={}}
    end
    for _,row in ipairs(source)do
        local id=identities[normalized(row[2])]or identities[normalized(row[3])]or row[1]
        local rarity,kind=row[4],row[5]
        reward[rarity][#reward[rarity]+1]=id;table.insert(src[rarity],1,id)
        shop[rarity][kind][#shop[rarity][kind]+1]=id
        metadata[id]={sourceId=row[2],rarity=rarity,type=kind,healing=row[6]}
    end
    for _,typed in pairs(shop)do for _,pool in pairs(typed)do
        table.sort(pool,function(a,b)return metadata[a].sourceId<metadata[b].sourceId end)
    end end
    pools.reward,pools.src,pools.shop,pools.cardSourceMetadata=reward,src,shop,metadata
    data.cards.sourcePools=pools
    return data
end
return M
