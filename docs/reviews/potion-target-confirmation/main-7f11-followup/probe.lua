local H=dofile('../natural_fixture.lua')
local setup,Run,Combat,eq,untouched=H.setup,H.Run,H.Combat,H.eq,H.untouched
local test,finish=H.suite('LUA_INTEGRATED_POTION_REVIEW')
for _,kind in ipairs({'up','endDrag'}) do
 test('orphan enemy '..kind..' does not become click-only confirmation',function()
  local h,u,p,r,e,click,tap=setup(true);tap('potion1',7);local z=h.run.combat.enemies[2].hp
  e('enemy2',kind,8);e('enemy2','click',8)
  eq(h.run.potions[1],'fire_potion');eq(h.run.combat.enemies[2].hp,z)
  if not u.potionAim then tap('potion1',9) end
  tap('enemy2',10);eq(h.run.potions[1],nil);eq(h.run.combat.enemies[2].hp,z-20)
 end)
end
test('genuine click-only enemy remains usable with paired bottle',function()
 local h,u,p,r,e,click,tap=setup(true);tap('potion1',7);local z=h.run.combat.enemies[2].hp
 click('enemy2');eq(h.run.potions[1],nil);eq(h.run.combat.enemies[2].hp,z-20)
end)
test('stale end-turn release does not execute through newer potion aim',function()
 local h,u,p,r,e,click,tap=setup(true);e('endTurn','down',6);e('endTurn','up',6);tap('potion1',7)
 local aim,turn=u.potionAim,h.run.combat.turn;assert(aim);e('endTurn','click',6)
 eq(h.run.combat.turn,turn);eq(u.potionAim,aim);eq(h.run.potions[1],'fire_potion')
end)
test('fresh end-turn still executes and cancels aim',function()
 local h,u,p,r,e,click,tap=setup(true);tap('potion1',7);local turn=h.run.combat.turn
 tap('endTurn',8);eq(h.run.combat.turn,turn+1);eq(u.potionAim,nil);eq(h.run.potions[1],'fire_potion')
end)
test('stale enemy EndDrag cannot cancel newer bottle aim',function()
 local h,u,p,r,e,click,tap=setup(true);assert(Run.obtainPotion(h.run,'fire_potion'));h:refresh()
 tap('potion1',7);e('enemy2','down',8);e('enemy2','up',8);tap('potion2',9);local aim=u.potionAim;assert(aim)
 e('enemy2','endDrag',8);eq(u.potionAim,aim);eq(Run.potionCount(h.run),2)
 tap('enemy2',10);eq(h.run.potions[1],'fire_potion');eq(h.run.potions[2],nil)
end)
test('current enemy EndDrag cancels aim and requires fresh bottle selection',function()
 local h,u,p,r,e,click,tap=setup(true);tap('potion1',7);e('enemy2','down',8);e('enemy2','up',8);e('enemy2','endDrag',8);e('enemy2','click',8)
 eq(u.potionAim,nil);eq(h.run.potions[1],'fire_potion');tap('enemy2',9);eq(h.run.potions[1],'fire_potion')
 tap('potion1',10);tap('enemy2',11);eq(h.run.potions[1],nil)
end)
for _,id in ipairs({'fire_potion','block_potion'}) do
 test('real discard and '..id..' refill invalidates aim without redraw',function()
  local h,u,p,r,e,click=setup();click('potion1');assert(Run.discardPotion(h.run,1));assert(Run.obtainPotion(h.run,id));local z=h.run.combat.enemies[2].hp
  click('enemy2');eq(h.run.potions[1],id);eq(h.run.combat.enemies[2].hp,z);eq(h.run.combat.player.block,0);eq(u.potionAim,nil)
 end)
end
test('pending enemy token cannot use same-slot same-ID refill',function()
 local h,u,p,r,e,click,tap=setup(true);tap('potion1',7);e('enemy2','down',8)
 assert(Run.discardPotion(h.run,1));assert(Run.obtainPotion(h.run,'fire_potion'))
 e('enemy2','up',8);e('enemy2','click',8);eq(h.run.potions[1],'fire_potion');u:render();eq(u.potionAim,nil)
 tap('potion1',9);tap('enemy2',10);eq(h.run.potions[1],nil)
end)
test('same-ID bottle switch changes slot but old enemy click cannot confirm',function()
 local h,u,p,r,e,click,tap=setup(true);assert(Run.obtainPotion(h.run,'fire_potion'));h:refresh()
 tap('potion1',7);e('enemy2','down',8);e('enemy2','up',8);tap('potion2',9);e('enemy2','click',8)
 eq(Run.potionCount(h.run),2);eq(u.potionAim.slot,2);tap('enemy2',10);eq(h.run.potions[1],'fire_potion');eq(h.run.potions[2],nil)
end)
test('old card release cannot cancel newer potion aim',function()
 local h,u,p,r,e,click,tap=setup(true);e('card1','down',6);e('card1','up',6);tap('potion1',7)
 local aim=u.potionAim;assert(aim);e('card1','click',6);eq(u.potionAim,aim);eq(u.selected,nil)
 tap('enemy2',8);eq(h.run.potions[1],nil)
end)
test('same bottle explicit click cancels without mutation',function()
 local h,u,p,r,e,click,tap=setup(true);local a,z=h.run.combat.enemies[1].hp,h.run.combat.enemies[2].hp
 tap('potion1',7);assert(u.potionAim);tap('potion1',8);eq(u.potionAim,nil);untouched(h,a,z)
end)
test('field click cancels aim without mutation',function()
 local h,u,p,r,e,click,tap=setup(true);local a,z=h.run.combat.enemies[1].hp,h.run.combat.enemies[2].hp
 tap('potion1',7);tap('playArea',8);eq(u.potionAim,nil);untouched(h,a,z)
end)
test('real poison transaction overflow is atomic and fresh retry succeeds',function()
 local h,u,p,r,e,click,tap=setup(true)
 assert(Run.discardPotion(h.run,1));assert(Run.obtainPotion(h.run,'poison_potion'));h:refresh();tap('potion1',7)
 local b=h.run.combat;assert(require('abyss_actor').applyPower(b,b.enemies[2],'poison',2147483647,b.player))
 local inv,energy,events=h.run.potions,b.energy,#b.events;local a,z=b.enemies[1].hp,b.enemies[2].hp
 e('enemy2','down',8);e('enemy2','up',8);local ok,why=e('enemy2','click',8)
 eq(ok,false);eq(why,'effect_overflow');eq(u.potionAim,nil);assert(not u.busy)
 eq(h.run.potions,inv);eq(h.run.potions[1],'poison_potion');eq(b.energy,energy);eq(#b.events,events)
 eq(b.enemies[1].hp,a);eq(b.enemies[2].hp,z);eq(b.enemies[2].statuses.poison,2147483647)
 e('enemy2','click',8);eq(h.run.potions,inv)
 tap('potion1',9);tap('enemy1',10);eq(h.run.potions[1],nil);eq(b.enemies[1].statuses.poison,6)
 eq(b.enemies[2].statuses.poison,2147483647);eq(b.energy,energy)
end)
test('presentation preparation failure preserves state and fresh retry succeeds',function()
 local h,u,p,r,e,click=setup();local b=h.run.combat;local a,z=b.enemies[1].hp,b.enemies[2].hp
 click('potion1');local render=u.render;u.render=function()error('TARGET_PREPARE_FAILURE')end
 local ok=e('enemy2','click');u.render=render;eq(ok,false);untouched(h,a,z);eq(u.potionAim,nil);assert(not u.busy)
 click('enemy2');untouched(h,a,z);click('potion1');click('enemy2');eq(b.enemies[2].hp,z-20)
end)
test('metadata-free Down Up Click still separates arming and confirmation',function()
 local h,u,p,r,e,click,tap=setup(true);tap('potion1');eq(h.run.potions[1],'fire_potion');tap('enemy2');eq(h.run.potions[1],nil)
end)
test('known Down Click without Up remains supported',function()
 local h,u,p,r,e,click,tap=setup(true);tap('potion1',7);e('enemy2','down',8);e('enemy2','click',8);eq(h.run.potions[1],nil)
end)
finish()
