"""Fixed319009 Maw/SpireGrowth A0, independent of product Lua/data.

The long arithmetic fixture starts at1000 HP only to observe eight moves. This
is a source model, not original-PC execution or a natural campaign route.
"""
import argparse
import json
from sts1_combat_gold import Random
from sts1_shapes import lua


def vector(seed, policy):
    hp_rng, ai = Random(seed), Random(seed)
    monster_hp = 300 if policy == 'maw' else hp_rng.integer(170, 170)
    history, roared, count, strength, constricted, health = [], False, 1, 0, 0, 1000

    def choose():
        nonlocal count
        number = ai.integer(0, 99)
        last = history[-1] if history else None
        if policy == 'maw':
            count += 1
            if not roared:
                move = 'roar'
            elif number < 50 and last != 'nom':
                move = 'nom'
            elif last in ('slam', 'nom'):
                move = 'drool'
            else:
                move = 'slam'
        elif number < 50 and history[-2:] != ['tackle', 'tackle']:
            move = 'tackle'
        elif not constricted and last != 'constrict':
            move = 'constrict'
        elif history[-2:] != ['smash', 'smash']:
            move = 'smash'
        else:
            move = 'tackle'
        history.append(move)
        return move, number

    move, number = choose()
    rows = []
    for _ in range(8):
        hits = count // 2 if move == 'nom' else 1 if move in ('slam', 'tackle', 'smash') else 0
        unit = (5 if move == 'nom' else 25) + strength if policy == 'maw' and hits else 16 if move == 'tackle' else 22 if move == 'smash' else 0
        loss = constricted + hits * unit
        health -= loss
        if move == 'roar':
            roared = True
        elif move == 'drool':
            strength += 3
        elif move == 'constrict':
            constricted += 10
        rows.append({'intent': move, 'primaryRoll': number, 'counterBefore': count if policy == 'maw' else 0,
                     'hits': hits, 'unitDamage': unit, 'playerLoss': loss, 'hpAfter': health,
                     'strengthAfter': strength, 'constrictedAfter': constricted})
        move, number = choose()
    return {'seed': str(seed), 'policy': policy, 'monsterHp': monster_hp,
            'hpRng': hp_rng.snapshot(), 'aiRng': ai.snapshot(), 'steps': rows,
            'nextIntent': move, 'nextCounter': count if policy == 'maw' else 0}


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--lua', action='store_true')
    args = parser.parse_args()
    values = [vector(seed, policy) for seed in (1, 42, 77) for policy in ('maw', 'spire_growth')]
    if args.lua:
        print('-- Generated by independent tools/oracles/sts1_maw_growth.py; not PC binary execution.\nreturn {\n'
              + ',\n'.join(lua(v) for v in values) + '\n}')
    else:
        print(json.dumps(values, indent=2))
