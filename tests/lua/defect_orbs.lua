package.path='src/lua/?.lua;build/lua/?.lua;'..package.path
local O=require('abyss_orbs')
local C=require('abyss_combat')
local R=require('abyss_sts_random')
local data=require('abyss_data')
local n=0
local function eq(a,b) assert(a==b,tostring(a)..' ~= '..tostring(b)) end
local function test(name,f) f(); n=n+1; print('ok '..n..' '..name) end
local function battle(slots,two)
 local s=C.new(data,{seed=42,enemies=two and {'jaw_worm','jaw_worm'} or {'jaw_worm'}})
 s.cardRandomRng=R.fromSeed("17")
 O.init(s,slots)
 return s
end
local function ch(s,k) return O.channel(s,k,C) end

test('zero slots rejects channel without random draw',function()
 local s=battle(0);eq(ch(s,'lightning'),false);eq(s.cardRandomRng.counter,0);eq(#s.orbs.balls,0)
end)
test('one slot overflows by evoking old orb',function()
 local s=battle(1);ch(s,'frost');ch(s,'dark');eq(s.player.block,5);eq(s.orbs.balls[1].kind,'dark')
end)
test('three slots preserve order on overflow',function()
 local s=battle(3);ch(s,'frost');ch(s,'dark');ch(s,'plasma');ch(s,'frost');eq(s.player.block,5);eq(s.orbs.balls[1].kind,'dark');eq(s.orbs.balls[3].kind,'frost')
end)
test('lightning passive ignores attack modifiers and consumes independent RNG even singleton',function()
 local s=battle(3);ch(s,'lightning');s.player.statuses.strength=90;s.player.statuses.weak=2;s.enemies[1].statuses.vulnerable=2
 local hp=s.enemies[1].hp;O.endTurn(s,C);eq(s.enemies[1].hp,hp-3);eq(s.cardRandomRng.counter,1)
end)
test('lightning evoke eight ignores thorns and Curl Up',function()
 local s=battle(3);ch(s,'lightning');s.enemies[1].statuses.thorns=9;s.enemies[1].statuses.curl_up=10
 local hp=s.player.hp;local enemy=s.enemies[1].hp;O.evoke(s,C);eq(s.player.hp,hp);eq(s.enemies[1].hp,enemy-8);eq(s.enemies[1].block,0)
end)
test('frost ignores dexterity and frail',function()
 local s=battle(3);s.player.statuses.dexterity=99;s.player.statuses.frail=3;ch(s,'frost');O.endTurn(s,C);eq(s.player.block,2);O.evoke(s,C);eq(s.player.block,7)
end)
test('negative focus clamps normal passive and evoke',function()
 local s=battle(3);ch(s,'frost');O.setFocus(s,-20);O.endTurn(s,C);O.evoke(s,C);eq(s.player.block,0)
end)
test('focus updates lightning and frost independently',function()
 local s=battle(3);ch(s,'frost');O.setFocus(s,2);O.endTurn(s,C);eq(s.player.block,4);O.evoke(s,C);eq(s.player.block,11)
end)
test('dark starts six and focus changes only future growth',function()
 local s=battle(3);ch(s,'dark');O.setFocus(s,2);eq(s.orbs.balls[1].stored,6);O.endTurn(s,C);eq(s.orbs.balls[1].stored,14);O.setFocus(s,-8);O.endTurn(s,C);eq(s.orbs.balls[1].stored,14)
end)
test('dark lowest HP selection and same HP uses list order',function()
 local s=battle(3,true);ch(s,'dark');s.enemies[1].hp=20;s.enemies[2].hp=20
 O.evoke(s,C);eq(s.enemies[1].hp,14);eq(s.enemies[2].hp,20)
end)
test('dark locks target when prepared and will not retarget',function()
 local s=battle(3,true);ch(s,'dark');s.enemies[1].hp=10;s.enemies[2].hp=20
 local a=O.prepareEvoke(s,true);s.enemies[2].hp=5;O.resolve(s,a,C);eq(s.enemies[1].hp,4);eq(s.enemies[2].hp,5)
end)
test('dead locked target is skipped without targeting survivor',function()
 local s=battle(3,true);ch(s,'dark');s.enemies[1].hp=10;s.enemies[2].hp=20
 local a=O.prepareEvoke(s,true);s.enemies[1].hp=0;O.resolve(s,a,C);eq(s.enemies[2].hp,20)
end)
test('dualcast same first orb twice leaving second intact',function()
 local s=battle(3);ch(s,'frost');ch(s,'plasma');O.dualcast(s,C);eq(s.player.block,10);eq(#s.orbs.balls,1);eq(s.orbs.balls[1].kind,'plasma')
end)
test('dualcast recomputes lowest HP after first enemy dies',function()
 local s=battle(3,true);ch(s,'dark');s.enemies[1].hp=5;s.enemies[2].hp=20;O.dualcast(s,C);eq(s.enemies[1].hp,0);eq(s.enemies[2].hp,14)
end)
test('last enemy death cancels remaining dualcast and later passive hits',function()
 local s=battle(3);ch(s,'lightning');ch(s,'lightning');s.enemies[1].hp=2;O.endTurn(s,C);eq(s.cardRandomRng.counter,1);eq(s.enemies[1].hp,0)
end)
test('plasma start turn and evoke ignore both signs of focus',function()
 local s=battle(3);ch(s,'plasma');O.setFocus(s,99);O.endTurn(s,C);eq(s.energy,3);O.startTurn(s,C);eq(s.energy,4);O.setFocus(s,-99);O.evoke(s,C);eq(s.energy,6)
end)
test('no orb evoke is safe and creates no RNG consumption',function()
 local s=battle(3);eq(O.evoke(s,C),false);eq(O.dualcast(s,C),false);eq(s.cardRandomRng.counter,0)
end)
test('dead player cancels passive and channel',function()
 local s=battle(3);ch(s,'plasma');s.player.hp=0;O.startTurn(s,C);eq(s.energy,3);eq(ch(s,'dark'),false)
end)
test('snapshot detached from live orbs',function()
 local s=battle(3);ch(s,'dark');local snap=O.snapshot(s);snap.balls[1].stored=999;eq(s.orbs.balls[1].stored,6)
end)
test('invalid kinds slots and unimplemented options explicitly reject',function()
 local s=C.new(data,{seed=42});assert(not pcall(O.init,s,11));assert(not pcall(O.init,s,3,{cables=true}));O.init(s,3);assert(not pcall(ch,s,'fake'))
end)
test('dark grows synchronously before queued earlier lightning kills final enemy',function()
 local s=battle(3);ch(s,'lightning');ch(s,'dark');s.enemies[1].hp=2
 O.endTurn(s,C);eq(s.enemies[1].hp,0);eq(s.orbs.balls[2].stored,12)
end)
test('missing API or RNG rejects normal evoke before removing orb',function()
 local s=battle(3);ch(s,'lightning');assert(not pcall(O.evoke,s,{}));eq(#s.orbs.balls,1)
 s.cardRandomRng=nil;assert(not pcall(O.evoke,s,C));eq(#s.orbs.balls,1)
end)
test('energy overflow rejects plasma evoke before consuming orb',function()
 local s=battle(3);ch(s,'plasma');s.energy=2147483647.0
 assert(not pcall(O.evoke,s,C));eq(#s.orbs.balls,1);eq(s.energy,2147483647.0)
end)
test('dark impulse affects only dark and clamps negative focus growth',function()
 local s=battle(3);ch(s,'dark');ch(s,'frost');ch(s,'dark');O.setFocus(s,2)
 O.darkImpulse(s);eq(s.orbs.balls[1].stored,14);eq(s.orbs.balls[3].stored,14);eq(s.player.block,0)
 O.setFocus(s,-9);O.darkImpulse(s);eq(s.orbs.balls[1].stored,14);eq(s.orbs.balls[3].stored,14)
end)
test('queued frost survives earlier lightning killing final enemy',function()
 local s=battle(3);ch(s,'lightning');ch(s,'frost');s.enemies[1].hp=1
 O.endTurn(s,C);eq(s.enemies[1].hp,0);eq(s.player.block,2)
end)
test('already prepared frost evoke survives victory but new actions cannot start',function()
 local s=battle(3);ch(s,'frost');local a=O.prepareEvoke(s,true);s.enemies[1].hp=0
 assert(O.resolve(s,a,C));eq(s.player.block,5);eq(ch(s,'frost'),false);eq(O.prepareEvoke(s,true),nil)
end)
test('already queued frost never resolves after player death',function()
 local s=battle(3);ch(s,'frost');local a=O.prepareEvoke(s,true);s.player.hp=0
 eq(O.resolve(s,a,C),false);eq(s.player.block,0)
end)
print('DEFECT_ORBS_PASS '..n)
