local testStart=dofile('tests/lua/support/game_ui_fixture.lua').start
local H = dofile("tests/lua/support/battle_action_fixture.lua")
local test, finish = H.suite("LUA_ACTION_COMPATIBILITY")
test("fresh paired end turn executes once", function()
    local h,u,p,e,t,d=H.setup();t("endTurn",7);d();assert(h.run.combat.turn==2)
end)
test("no-pointer host keeps click-only end turn", function()
    local h,r=H.F.fixture();assert(testStart(h));assert(H.Run.startCombat(h.run,"cultist_solo"));h:refresh()
    r:GetChild("battlePanel"):GetChild("endTurn").click();assert(h.run.combat.turn==2)
end)
test("pointer-capable host keeps click-only actions after real card pointers", function()
    local h,u,p,e,t,d=H.setup();t("card1",8);t("playArea",8);d()
    p:GetChild("endTurn").click();assert(h.run.combat.turn==2)
end)
test("pointer-capable host keeps click-only actions after real potion pointers", function()
    local h,u,p,e,t,d=H.setup();assert(H.Run.obtainPotion(h.run,"energy_potion"));h:refresh()
    t("potion1",8);dofile("tests/lua/support/confirm_potion_popup.lua")(u,p,8)
    d();assert(h.run.combat.energy==5)
    p:GetChild("endTurn").click();assert(h.run.combat.turn==2)
end)
test("metadata-free Down Up Click and same-ID reuse stay valid", function()
    local h,u,p,e,t,d=H.setup();t("endTurn",nil);d();assert(h.run.combat.turn==2)
    t("endTurn",nil);d();assert(h.run.combat.turn==3)
end)
test("harmless redraws retain held and released action identity", function()
    local h,u,p,e,t,d=H.setup();e("endTurn","down",7);h:refresh();u:render()
    e("endTurn","up",7);h:refresh();u:render();e("endTurn","click",7);d()
    assert(h.run.combat.turn==2)
end)
test("fresh reward skip after modal close keeps the current deck", function()
    local h,u,p,e,t,d,deck=H.reward();local n=#h.run.deck;deck();t("skip",7)
    assert(h.run.phase=="reward" and p:GetChild('rewardList').visible and #h.run.deck==n)
end)
test("reward skip supports mixed-host Click after physical card input", function()
    local h,u,p=H.reward();p:GetChild("skip").click();assert(h.run.phase=="reward" and p:GetChild('rewardList').visible)
end)
finish()
