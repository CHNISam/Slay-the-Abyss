local H=dofile('tests/helpers/act2_event_relics.lua')
local eq,same,test=H.eq,H.same,H.test
local function repeats(s)local n=0;for _,e in ipairs(s.events)do if e.kind=='relic_repeat'then n=n+1 end end;return n end
test('Necronomicon actual two-cost attack repeats once per turn, copy shares UUID and purges without extra energy',function()
 local r,s=H.battle({'Necronomicon','Lantern'},{'heavy_blade','heavy_blade'})
 local before=s.enemies[1].hp;assert(H.play(r,'heavy_blade'));eq(before-s.enemies[1].hp,28);eq(s.energy,2);eq(repeats(s),1)
 assert(H.play(r,'heavy_blade'));eq(before-s.enemies[1].hp,42);eq(s.energy,0);eq(repeats(s),1);eq(#s.discard,2);eq(#s.exhaust,0)
 local plays={};for _,e in ipairs(s.events)do if e.kind=='play'then plays[#plays+1]=e.detail end end;eq(#plays,3);assert(plays[1].uid~=plays[2].uid)
 assert(H.Run.endTurn(r));eq(s.turn,2);eq(s.relicCombat.necronomiconActivated,true)
end)
test('Necronomicon excludes one-cost and source-free zero-cost cards without spending its activation',function()
 local r,s=H.battle({'Necronomicon'},{'strike','heavy_blade'})
 local first=H.card(r,'heavy_blade');first.costForTurn=0 -- explicit temporary-cost boundary fixture, not acquisition evidence
 local hp=s.enemies[1].hp;assert(H.play(r,'strike'));eq(hp-s.enemies[1].hp,6);eq(repeats(s),0)
 hp=s.enemies[1].hp;assert(H.play(r,'heavy_blade'));eq(hp-s.enemies[1].hp,14);eq(repeats(s),0);eq(s.relicCombat.necronomiconActivated,true)
end)
test('Necronomicon X attack captures energyOnUse before payment and repeats same X without spending twice',function()
 local r,s=H.battle({'Necronomicon'},{'whirlwind'})
 local before=s.enemies[1].hp;assert(H.play(r,'whirlwind'));eq(before-s.enemies[1].hp,30);eq(s.energy,0);eq(repeats(s),1);eq(#s.discard,1)
end)
test('Necronomicurse is genuinely unplayable and native TrueGrit exhaust recreates one fresh hand card',function()
 local r,s=H.battle({'Necronomicon'},{'true_grit'})
 H.reject(r,function()return H.Run.play(r,H.card(r,'necronomicurse').uid,1)end,'unplayable_card')
 local old=H.card(r,'necronomicurse');local nextUid=s.nextUid;assert(H.play(r,'true_grit'))
 eq(#s.exhaust,1);eq(s.exhaust[1].uid,old.uid);eq(#s.hand,1);eq(s.hand[1].cardId,'necronomicurse');eq(s.hand[1].uid,nextUid)
 eq(s.hand[1].upgraded,false);eq(s.player.block,7)
end)
test('queued TrueGrit exhaust with FNP/DarkEmbrace keeps source power hooks before new curse copy',function()
 local r,s=H.battle({'Necronomicon'},{'true_grit'})
 H.C.applyEffects(s,{{op='gainExhaustPower',status='feel_no_pain',value=3},{op='gainExhaustPower',status='dark_embrace',value=1}},s.player,s.player)
 local old=H.card(r,'necronomicurse');assert(H.play(r,'true_grit'));eq(s.exhaust[1].uid,old.uid)
 local seen;for _,c in ipairs(s.hand)do if c.cardId=='necronomicurse'and c.uid~=old.uid then seen=c end end;assert(seen)
 eq(s.player.block,10)
end)
test('late repeated-card failure rolls back energy, activation, deck/piles, RNG and captured same-instance copies',function()
 local r,s=H.battle({'Necronomicon'},{'heavy_blade'});local before=H.C.copy(r,{[r.data]=r.data});local original=H.E.emit;local plays=0
 H.E.emit=function(state,kind,detail)
  local value=original(state,kind,detail);if kind=='play'then plays=plays+1;if plays==2 then error('late repeated play')end end;return value
 end
 local called=pcall(H.play,r,'heavy_blade');H.E.emit=original;eq(called,false);eq(plays,2);same(r,before)
 assert(H.play(r,'heavy_blade'));eq(repeats(r.combat),1)
end)
test('active real book obtain publishes ownership without replaying opening benefits, loss/reacquire resets new book activation',function()
 local r,s=H.battle({}, {'heavy_blade','heavy_blade'});local hand=#s.hand;local oldDeck=#r.deck
 assert(H.Run.obtainRelic(r,'Enchiridion'));assert(H.Run.obtainRelic(r,'MutagenicStrength'));s=r.combat;eq(#s.hand,hand);eq(s.player.statuses.strength,nil)
 assert(H.Run.obtainRelic(r,'Necronomicon'));s=r.combat;eq(#r.deck,oldDeck+1);eq(#s.hand,hand)
 assert(H.play(r,'heavy_blade'));eq(repeats(s),1);eq(s.relicCombat.necronomiconActivated,false)
 assert(H.Run.loseRelic(r,'Necronomicon'));assert(H.Run.obtainRelic(r,'Necronomicon'));s=r.combat;eq(s.relicCombat.necronomiconActivated,true)
end)
H.finish('ACT2_EVENT_RELIC_NECRONOMICON')
