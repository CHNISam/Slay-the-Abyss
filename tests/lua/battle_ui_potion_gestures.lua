local H = dofile("tests/lua/support/potion_gesture_fixture.lua")
local F, Run, fixture = H.F, H.Run, H.setup
local test, finish = H.suite("LUA_POTION_GESTURES")

test("modal active rejects stale callback",function()
    local h,u,p,e,t,d,deck,r,emit=fixture()
    emit("potion1","down",7);assert(h:openDeck())
    emit("potion1","up",7);emit("potion1","click",7)
    assert(h.run.potions[1]=="energy_potion" and h.run.combat.energy==3)
end)
test("modal open close cancels held physical potion sequence",function()
    local h,u,p,e,t,d,deck,r,emit=fixture()
    emit("potion1","down",7);deck()
    emit("potion1","up",7);emit("potion1","click",7)
    assert(h.run.potions[1]=="energy_potion", "old modal-interrupted pointer consumed potion; energy="..h.run.combat.energy)
end)
test("resize cancels held physical potion sequence",function()
    local h,u,p,e,t,d,deck,r,emit=fixture()
    emit("potion1","down",7);h:resize(1600,900)
    emit("potion1","up",7);emit("potion1","click",7)
    assert(h.run.potions[1]=="energy_potion", "old resize-interrupted pointer consumed potion")
end)
test("real card animation cancels held physical potion sequence",function()
    local h,u,p,e,t,d,deck,r,emit=fixture()
    emit("potion1","down",7);t("card1",8);t("card1",8)
    assert(u.busy and h.run.combat.player.block==5);d()
    emit("potion1","up",7);emit("potion1","click",7)
    assert(h.run.potions[1]=="energy_potion", "old pre-animation pointer consumed potion; energy="..h.run.combat.energy)
end)
test("real end turn cancels held physical potion sequence",function()
    local h,u,p,e,t,d,deck,r,emit=fixture()
    emit("potion1","down",7);emit("endTurn","down",8);emit("endTurn","up",8);emit("endTurn","click",8);d()
    assert(h.run.combat.turn==2)
    emit("potion1","up",7);emit("potion1","click",7)
    assert(h.run.potions[1]=="energy_potion", "old turn pointer consumed potion in turn "..h.run.combat.turn)
end)
test("old run pointer cannot consume new run bottle after real defeat restart",function()
    local h,u,p,e,t,d,deck,r,emit=fixture({"defend","defend"},{"jaw_worm"})
    -- Controlled one-HP setup, subsequent turn/defeat/restart/map entry are real.
    h.run.combat=F.Combat.new(F.Data,{hp=1,deck={"defend","defend"},enemies={"jaw_worm"}});h:refresh()
    local old=h.run
    emit("potion1","down",7);emit("endTurn","down",8);emit("endTurn","up",8);emit("endTurn","click",8);d()
    assert(h.mode=="defeat" and h.run==old)
    assert(r:GetChild("menuPanel"):GetChild("start"):GetChild("hit").click({touchId=8}))
    assert(h.run~=old and h.mode=="map")
    assert(h.mapUI:choose(F.Nodes.available(h.run,h.map)[1].id))
    -- There is no natural acquisition chain yet. Explicit real inventory grant.
    assert(Run.obtainPotion(h.run,"block_potion"));h:refresh()
    emit("potion1","up",7);emit("potion1","click",7)
    assert(h.run.potions[1]=="block_potion", "old run pointer consumed new run Block Potion; block="..h.run.combat.player.block)
end)
test("resize between Up and Click cancels the released potion",function()
    local h,u,p,e,t,d,deck,r,emit=fixture()
    emit("potion1","down",7); emit("potion1","up",7); h:resize(1600,900)
    emit("enemy1","down",8); emit("potion1","click",7)
    assert(h.run.potions[1]=="energy_potion" and h.run.combat.energy==3)
end)
test("deck between Up and Click cancels the released potion",function()
    local h,u,p,e,t,d,deck,r,emit=fixture()
    emit("potion1","down",7); emit("potion1","up",7); deck()
    emit("potion1","click",7)
    assert(h.run.potions[1]=="energy_potion" and h.run.combat.energy==3)
end)
test("EndDrag cancels held or released potion ownership",function()
    for _,released in ipairs({false,true}) do
        local h,u,p,e,t,d,deck,r,emit=fixture()
        emit("potion1","down",7)
        if released then emit("potion1","up",7) end
        emit("potion1","endDrag",7); emit("potion1","up",7); emit("potion1","click",7)
        assert(h.run.potions[1]=="energy_potion" and h.run.combat.energy==3)
    end
end)
finish()
