local F=dofile('tests/lua/support/event_combat_route_fixture.lua')
local Run,N,C,R=F.Run,F.N,F.C,F.R
local run,map=F.event('42','colosseum')
assert(run.nodeFlow.event.stage=='intro'and run.hp==F.D.rules.player.maxHp)
local deck=C.copy(run.deck);local queue=C.copy(run.encounters);local gold=run.gold
assert(not N.chooseEvent(run,'leave'))
assert(N.chooseEvent(run,'continue'));assert(N.chooseEvent(run,'fight'))
assert(run.phase=='combat'and run.eventCombat.rewardAllowed==false and run.encounterTier=='normal')
assert(run.combat.monsterHpRng.counter==2)
assert(run.combat.enemies[1].definitionId=='blue_slaver'and run.combat.enemies[2].definitionId=='red_slaver')
local card=R.snapshot(run.cardRng)
local Cards,Potion=require('abyss_card_pool'),require('abyss_potion_rewards')
local oldCard,oldPotion=Cards.prepareRewards,Potion.prepare;local potionCount
Cards.prepareRewards=function()error('FIRST_COLOSSEUM_MUST_NOT_GENERATE_CARDS')end
Potion.prepare=function(owner,count,context)potionCount=count;return oldPotion(owner,count,context)end
local ok,why=pcall(F.playStarterBattle,run)
Cards.prepareRewards,Potion.prepare=oldCard,oldPotion;assert(ok,why)
assert(run.phase=='node'and run.nodeFlow.event.stage=='post_combat'and run.hp==15)
assert(run.lastResult.outcome=='victory'and run.victories==1)
assert(run.rewards==nil and run.eventCombat==nil and not run.nodeFlow.eventCombat)
assert(potionCount==0);F.same(R.snapshot(run.cardRng),card);F.same(run.deck,deck);F.same(run.encounters,queue);assert(run.gold==gold)
local continuation=run.nodeFlow.event.roomContinuation
assert(continuation.monsterHpRng.counter==2)
local shuffle=R.cloneState(run.combat.shuffleRng);R.randomLongHex(shuffle)
F.same(continuation.shuffleRng,R.snapshot(shuffle));assert(continuation.aiRng.counter==8)
assert(not N.completeCombat(run,map),'first fight may not complete the event')
assert(not Run.leaveCombatRewards(run),'first fight has no hidden reward screen')
local prepared=assert(require('abyss_event_combat_routes').prepare(run,'Colosseum Nobs',18,Run.roomStreams,run.miscRng,continuation))
local hp=R.restore(continuation.monsterHpRng);R.randomInt(hp,6)
local expectedTask=R.randomIntBetween(hp,54,60);local expectedNob=R.randomIntBetween(hp,82,86)
assert(prepared.prepared.actors[1].definitionId=='taskmaster'and prepared.prepared.actors[1].hp==expectedTask)
assert(prepared.prepared.actors[2].definitionId=='gremlin_nob'and prepared.prepared.actors[2].hp==expectedNob)
F.same(prepared.prepared.monsterHpRng,R.snapshot(hp));assert(hp.counter==5)
local accepted,reason=N.chooseEvent(run,'fight')
assert(accepted,reason) -- all original reward relics now have production bindings
assert(run.phase=='combat'and run.eventCombat.round==2 and #run.eventCombat.relics==2)
assert(run.eventCombat.relics[1].rarity=='rare'and run.eventCombat.relics[2].rarity=='uncommon')
assert(run.eventCombat.gold==100 and run.combat.monsterHpRng.counter==5)
-- A public Smoke Bomb command exits the second wave, never reopens wave one.
local escaped,slot=Run.obtainPotion(run,'smoke_bomb');assert(escaped,slot)
assert(Run.usePotion(run,slot));assert(run.phase=='map'and not run.eventCombat and not run.rewards)
assert(N.completeCombat(run,map));assert(run.nodeFlow.complete and #N.available(run,map)>0)
local paid,paidMap=F.event('42','masked_bandits')
local before=R.snapshot(paid.miscRng)
assert(N.chooseEvent(paid,'pay'));assert(paid.gold==0)
assert(N.chooseEvent(paid,'continue'));assert(N.chooseEvent(paid,'continue'))
assert(N.chooseEvent(paid,'leave'));assert(paid.phase=='map'and paid.nodeFlow.complete)
F.same(R.snapshot(paid.miscRng),before)
assert(not N.chooseEvent(paid,'fight'),'terminal paid event cannot reopen combat')
print('EVENT_COMBAT_ROUTE_COLOSSEUM_PASS legal starter victory, no-reward reopen, original continuation and second-fight transaction')
