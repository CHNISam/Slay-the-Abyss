local H = dofile("tests/lua/support/battle_action_fixture.lua")
local test, finish = H.suite("LUA_ACTION_GESTURES")
test("end turn cannot survive a real deck modal round trip", function()
    local h,u,p,e,t,d,deck=H.setup();e("endTurn","down",7);deck()
    e("endTurn","up",7);e("endTurn","click",7);assert(h.run.combat.turn==1)
    t("endTurn",7);d();assert(h.run.combat.turn==2)
end)
test("older end turn pointer cannot skip a newer player turn", function()
    local h,u,p,e,t,d=H.setup();e("endTurn","down",7);t("endTurn",8);d()
    assert(h.run.combat.turn==2);e("endTurn","up",7);e("endTurn","click",7)
    assert(h.run.combat.turn==2 and h.run.combat.player.hp==80)
end)
test("real card playback cancels an older action pointer", function()
    local h,u,p,e,t,d=H.setup();e("endTurn","down",7);t("card1",8);t("playArea",8)
    assert(u.busy and h.run.combat.player.block==5);d()
    e("endTurn","up",7);e("endTurn","click",7);assert(h.run.combat.turn==1)
end)
test("resize cancels the held action even after unrelated target Down", function()
    local h,u,p,e,t,d=H.setup();e("endTurn","down",7);h:resize(1600,900)
    e("enemy1","down",8);e("endTurn","up",7);e("endTurn","click",7)
    assert(h.run.combat.turn==1)
end)
test("actions remain rejected while the deck is open", function()
    local h,u,p,e=H.setup();e("endTurn","down",7);assert(h:openDeck())
    e("endTurn","up",7);e("endTurn","click",7);assert(h.run.combat.turn==1)
end)
test("actions remain rejected during real playback", function()
    local h,u,p,e,t=H.setup();e("endTurn","down",7);t("card1",8);t("playArea",8)
    assert(u.busy);e("endTurn","up",7);e("endTurn","click",7)
    assert(h.run.combat.turn==1)
end)
test("reward skip cannot survive a real deck modal round trip", function()
    local h,u,p,e,t,d,deck=H.reward();local rewards=h.run.rewards
    e("skip","down",7);deck();e("skip","up",7);e("skip","click",7)
    assert(h.run.phase=="reward" and h.run.rewards==rewards)
    assert(p:GetChild('rewardStage').visible)
    t("skip",7);assert(h.run.phase=="reward" and p:GetChild('rewardList').visible and not rewards.cardResolved)
end)
test("new run rejects an older end turn pointer after real defeat restart", function()
    local h,u,p,e,t,d,deck,r=H.setup({"defend"},{"jaw_worm"})
    h.run.combat=H.F.Combat.new(H.F.Data,{hp=1,deck={"defend"},enemies={"jaw_worm"}});h:refresh()
    local old=h.run;e("endTurn","down",7);t("endTurn",8);d();assert(h.mode=="defeat")
    local restart = r:GetChild("menuPanel"):GetChild("start"):GetChild("hit")
    restart.listeners.down({touchId=8}); restart.listeners.up({touchId=8})
    assert(restart.click({touchId=8}))
    assert(h.run~=old and h.mapUI:choose(H.F.Nodes.available(h.run,h.map)[1].id))
    e("endTurn","up",7);e("endTurn","click",7);assert(h.run.combat.turn==1)
end)
finish()
