local H = dofile("tests/lua/support/potion_targeting_fixture.lua")
local setup,Run,Combat,F,eq,untouched = H.setup,H.Run,H.Combat,H.F,H.eq,H.untouched
local test,finish = H.suite("LUA_POTION_TARGET_STALE")

test('card release predating bottle cannot cancel the newer potion intent',function()
  local h,u,p,r,e,click,tap=setup(true);e('card1','down',6);e('card1','up',6);tap('potion1',7)
  local pending=u.potionAim;assert(pending);e('card1','click',6);eq(u.potionAim,pending);eq(u.selected,nil)
  tap('enemy2',8);eq(h.run.potions[1],nil)
end)
test('older bottle sequence cannot cancel a newer same-slot pending intent',function()
  local h,u,p,r,e,click,tap=setup(true);e('potion1','down',6);e('potion1','up',6);tap('potion1',7)
  local pending=u.potionAim;e('potion1','click',6);eq(u.potionAim,pending);tap('enemy2',8);eq(h.run.potions[1],nil)
end)
test('new turn proactively clears pending during update',function()
  local h,u,p,r,e,click=setup();click('potion1');assert(Run.endTurn(h.run));h:update(.01)
  eq(u.potionAim,nil);eq(h.run.potions[1],'fire_potion')
end)
test('pending enemy touch cannot use a real same-ID refill',function()
  local h,u,p,r,e,click,tap=setup(true);tap('potion1',7);e('enemy2','down',8)
  assert(Run.discardPotion(h.run,1));assert(Run.obtainPotion(h.run,'fire_potion'))
  local hp=h.run.combat.enemies[2].hp
  e('enemy2','up',8);e('enemy2','click',8)
  eq(h.run.potions[1],'fire_potion');eq(h.run.combat.enemies[2].hp,hp)
  h:update(.01);eq(u.potionAim,nil)
  tap('potion1',9);tap('enemy2',10);eq(h.run.potions[1],nil);eq(h.run.combat.enemies[2].hp,hp-20)
end)
test('overlay invalidates enemy release even if a new bottle is armed',function()
  local h,u,p,r,e,click,tap=setup(true);tap('potion1',7);e('enemy2','down',8);e('enemy2','up',8)
  assert(h:openDeck());assert(h:closeDeck());tap('potion1',9);e('enemy2','click',8);eq(h.run.potions[1],'fire_potion')
  tap('enemy2',10);eq(h.run.potions[1],nil)
end)
finish()
