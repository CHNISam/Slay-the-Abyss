local F=dofile('tests/lua/support/game_ui_fixture.lua')
local Help=dofile('tests/lua/support/hidden_menu_help.lua')
local host,root=F.fixture()
assert(F.start(host))
assert(require('abyss_run').startCombat(host.run,'cultist_solo'));host:refresh()
local run,battle,map=host.run,host.run.combat,host.map
local hp,gold,energy=run.hp,run.gold,battle.energy
local function click(box)return box:GetChild('hit').click()end
assert(click(root:GetChild('exitEntry'):GetChild('open')))
assert(host.menuOpen and host.exitOpen,'menu entry must open the approved menu before exit confirmation')
local menu=root:GetChild('runMenu')
assert(menu.visible and not root:GetChild('exitPanel').visible)
Help.rejected(host,root)
Help.internalGuideFixture(host,root)
assert(host.controlsOpen and root:GetChild('exitPanel'):GetChild('guide').visible)
assert(not host:confirmExit())
assert(host:closeExit() and host.menuOpen and not host.controlsOpen)
assert(click(menu:GetChild('map')))
assert(host.routeOpen and root:GetChild('mapPanel').visible and not host.mapUI.navigationEnabled)
assert(not host:confirmExit())
assert(click(root:GetChild('mapPanel'):GetChild('previewBack')))
assert(not host.routeOpen and host.menuOpen)
assert(click(menu:GetChild('abandon')))
assert(not host.menuOpen and root:GetChild('exitPanel').visible)
assert(host:closeExit())
assert(host.run==run and host.run.combat==battle and host.map==map)
assert(run.hp==hp and run.gold==gold and battle.energy==energy)
assert(click(root:GetChild('exitEntry'):GetChild('open')))
assert(click(menu:GetChild('resume')) and not host.exitOpen and not host.menuOpen)
print('UI_FINAL_MENU_PASS approved menu, hidden help, internal guide isolation, map preview, separate confirmation, unchanged resources')
