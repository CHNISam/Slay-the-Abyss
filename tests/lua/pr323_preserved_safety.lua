-- Six offline regressions from PR323 02ea6bf. Public scope approval stays pending.
local H=dofile('tests/lua/support/battle_gesture_fixture.lua')
local R,C,D=require('abyss_run'),require('abyss_combat'),require('abyss_data')
local passed,failed=0,0
local function test(name,fn)
 local ok,why=pcall(fn)
 if ok then passed=passed+1;print('PASS preserved safety '..name)
 else failed=failed+1;print('FAIL preserved safety '..name..': '..tostring(why))end
end
local function drag(e,touch)
 e('card1','down',touch);e('card1','drag',touch,0,0);e('dragLayer','up',touch,0,0)
end
test('metadata-free drag consumes first ambiguous Click and permits deliberate retry',function()
 local h,u,p,e,_,drain=H.setup({'defend','defend'})
 drag(e,nil);drain();assert(h.run.combat.turn==1)
 p:GetChild('endTurn').click()
 assert(h.run.combat.turn==1,'anonymous drag trailing Click ended turn')
 p:GetChild('endTurn').click();assert(h.run.combat.turn==2,'deliberate anonymous retry stayed locked')
end)
test('independent anonymous action cannot revive named drag origin',function()
 local h,u,p,e,_,drain=H.setup({'defend','defend'})
 drag(e,7);drain();p:GetChild('endTurn').click();drain();assert(h.run.combat.turn==2)
 e('endTurn','click',7);e('endTurn','click',7)
 assert(h.run.combat.turn==2,'old drag touch ended another turn')
end)
test('resize cancellation requires fresh owned Down, never anonymous Click',function()
 local h,u,p,e,tap=H.setup({'defend','defend'})
 e('card1','down',7);e('card1','drag',7,0,0);h:resize(1600,900)
 assert(u.suppressClick==true and not u.gesture and h.run.combat.energy==3)
 p:GetChild('endTurn').click();p:GetChild('endTurn').click()
 assert(u.suppressClick==true and h.run.combat.turn==1,'anonymous Click cleared resize barrier')
 tap('endTurn',8);assert(h.run.combat.turn==2,'fresh owned Down did not recover')
end)
test('old combat drag touch cannot skip newly opened reward picker',function()
 local h,u,p,e,_,drain=H.setup({'bludgeon'},{'acid_slime_s'})
 local enemy=p:GetChild('enemy1')
 e('card1','down',7);e('card1','drag',7,enemy.x,enemy.y);e('dragLayer','up',7,enemy.x,enemy.y);drain()
 assert(h.run.phase=='reward' and u.rewardScreen=='list')
 p:GetChild('cardReward').click();assert(u.rewardScreen=='cards')
 e('skip','click',7);e('skip','click',7)
 assert(u.rewardScreen=='cards','old combat touch skipped reward picker')
 p:GetChild('skip').click();assert(u.rewardScreen=='list','fresh anonymous reward retry stayed locked')
end)
test('existing competition core admission guard rejects Raiden without changing full-source',function()
 local ok=pcall(R.new,D,42,{character='raiden',experimental=true,campaign=true,campaignProfile='competition-two-act'})
 assert(not ok,'competition Run.new admitted Raiden through direct options')
 local dev=R.new(D,42,{character='raiden',experimental=true,campaign=true,campaignProfile='full-source'})
 assert(dev.character=='raiden' and dev.data.originalV4Role=='RD','retained development role was removed')
end)
test('Pear updates active combat health owner rather than stale Run ledger',function()
 local r=R.new(D,42);r.hp=30;assert(R.startCombat(r,'cultist_solo'))
 C.damage(r.combat,r.combat.enemies[1],r.combat.player,5,true)
 assert(r.combat.player.hp==25 and r.hp==30)
 assert(R.obtainRelic(r,'Pear'))
 assert(r.maxHp==90 and r.hp==35 and r.combat.player.maxHp==90 and r.combat.player.hp==35,
  'Pear changed stale Run health, not current combat owner')
end)
print('PR323_PRESERVED_SAFETY_PASS '..passed..' FAIL '..failed)
assert(failed==0,'preserved safety regressions failed')
