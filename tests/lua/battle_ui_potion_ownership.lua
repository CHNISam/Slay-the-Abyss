local H = dofile("tests/lua/support/potion_gesture_fixture.lua")
local Run, fixture = H.Run, H.setup
local test, finish = H.suite("LUA_POTION_OWNERSHIP")

test("old held pointer cannot consume different real-command slot refill",function()
    local h,u,p,e,t,d,deck,r,emit,tap=fixture()
    emit("potion1","down",7)
    tap(8);d();assert(h.run.potions[1]==nil and h.run.combat.energy==5)
    local ok,slot=Run.obtainPotion(h.run,"block_potion");assert(ok and slot==1);h:refresh()
    emit("potion1","up",7);emit("potion1","click",7)
    assert(h.run.potions[1]=="block_potion", "old energy-potion pointer consumed new Block Potion; block="..h.run.combat.player.block)
end)
test("old held pointer cannot consume same-ID real-command slot refill",function()
    local h,u,p,e,t,d,deck,r,emit,tap=fixture()
    emit("potion1","down",7)
    tap(8);d();assert(h.run.potions[1]==nil and h.run.combat.energy==5)
    assert(Run.obtainPotion(h.run,"energy_potion"));h:refresh()
    emit("potion1","up",7);emit("potion1","click",7)
    assert(h.run.potions[1]=="energy_potion", "old pointer consumed replenished same-ID Energy Potion; energy="..h.run.combat.energy)
end)
test("direct real-command same-ID refill invalidates inventory identity without a render",function()
    local h,u,p,e,t,d,deck,r,emit,tap=fixture()
    emit("potion1","down",7); emit("potion1","up",7)
    assert(Run.usePotion(h.run,1)); assert(Run.obtainPotion(h.run,"energy_potion"))
    emit("potion1","click",7)
    assert(h.run.potions[1]=="energy_potion" and h.run.combat.energy==5)
    tap(8); d(); assert(h.run.potions[1]==nil and h.run.combat.energy==7)
end)
test("foreign and missing Click cannot consume a released potion token",function()
    local h,u,p,e,t,d,deck,r,emit=fixture()
    emit("potion1","down",7); emit("potion1","up",7)
    emit("potion1","click",8); p:GetChild("potion1").click()
    assert(h.run.potions[1]=="energy_potion" and h.run.combat.energy==3)
    emit("potion1","click",7); d(); assert(h.run.combat.energy==5)
end)
test("old pointer cannot cancel or consume a newer same-slot pointer",function()
    local h,u,p,e,t,d,deck,r,emit=fixture()
    emit("potion1","down",7); deck(); emit("potion1","down",8)
    emit("potion1","up",7); emit("potion1","endDrag",7); emit("potion1","click",7)
    emit("potion1","up",8); emit("potion1","click",7)
    assert(h.run.potions[1]=="energy_potion" and h.run.combat.energy==3)
    emit("potion1","click",8); d(); assert(h.run.combat.energy==5)
end)
test("cancelled pointer cannot fall back through an unobserved potion slot",function()
    local h,u,p,e,t,d,deck,r,emit,tap=fixture()
    assert(Run.obtainPotion(h.run,"block_potion")); h:refresh()
    emit("potion1","down",7); deck(); emit("enemy1","down",8)
    emit("potion2","up",7); emit("potion2","click",7); p:GetChild("potion2").click()
    assert(h.run.potions[2]=="block_potion" and h.run.combat.player.block==0)
    tap(8,2); d(); assert(h.run.combat.player.block==12)
end)
test("consumed Up and Click cannot replay after replenishing the same bottle",function()
    local h,u,p,e,t,d,deck,r,emit,tap=fixture()
    tap(7); d(); assert(Run.obtainPotion(h.run,"energy_potion")); h:refresh()
    emit("potion1","up",7); emit("potion1","click",7)
    assert(h.run.potions[1]=="energy_potion" and h.run.combat.energy==5)
    tap(7); d(); assert(h.run.potions[1]==nil and h.run.combat.energy==7)
end)
test("a Down on an empty slot cannot claim a later acquisition",function()
    local h,u,p,e,t,d,deck,r,emit,tap=fixture()
    emit("potion2","down",7)
    assert(Run.obtainPotion(h.run,"block_potion")); h:refresh()
    emit("potion2","up",7); emit("potion2","click",7)
    assert(h.run.potions[2]=="block_potion" and h.run.combat.player.block==0)
    tap(8,2); d(); assert(h.run.combat.player.block==12)
end)
test("potion Down alone cannot authorize Click before its matching Up",function()
    local h,u,p,e,t,d,deck,r,emit=fixture()
    emit("potion1","down",7); emit("potion1","click",7)
    assert(h.run.potions[1]=="energy_potion" and h.run.combat.energy==3)
    emit("potion1","up",7); emit("potion1","click",7); d()
    assert(h.run.potions[1]==nil and h.run.combat.energy==5)
end)
finish()
