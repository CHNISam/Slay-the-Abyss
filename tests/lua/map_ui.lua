local Map = require("abyss_map")
local MapUI = require("abyss_map_ui")
local Theme = require("abyss_theme")
local Layout = require("abyss_map_layout")
local data = require("abyss_data")
local count = 0
local function test(name, run) run(); count = count + 1; print("ok map UI " .. count .. " - " .. name) end
local function control()
    local self = { children = {}, visible = true, text = "", localScaleX = 1, localScaleY = 1 }
    function self:GetChild(name) return self.children[name] end
    function self:SetVisible(value) assert(type(value) == "boolean"); self.visible = value end
    function self:SetAnchoredPosition(x, y) self.x, self.y = x, y end
    function self:SetSizeDelta(w, h) self.w, self.h = w, h end
    function self:SetImage(source, id) assert(source == "static"); self.image = id end
    function self:AddCursorEventListener(event, fn) assert(event == "click"); assert(not self.click); self.click = fn end
    return self
end
local function mock()
    -- This control tree is generated by the JS test directly from mapLayout().
    local tree = require("abyss_map_controls")
    local function create(definition)
        local result = control()
        local p, s = definition.position or {0, 0}, definition.size
        result:SetAnchoredPosition(p[1], p[2])
        result:SetSizeDelta(s[1], s[2])
        result.visible = definition.visible ~= false
        for _, c in ipairs(definition.children or {}) do result.children[c.name] = create(c) end
        return result
    end
    local root = control()
    for _, definition in ipairs(tree.controls) do root.children[definition.name] = create(definition) end
    return root
end
local function makeUI(root, map, callback)
    return MapUI.new(root, map, callback, "click", {
        imageSource = "static",
        color = function(r, g, b, a)
            for _, n in ipairs({r, g, b, a}) do assert(n >= 0 and n <= 255 and n % 1 == 0) end
            return {r = r, g = g, b = b, a = a}
        end,
    })
end
local function panel(root) return root:GetChild("stage"):GetChild("mapPanel") end
local function click(root, name) return panel(root):GetChild(name):GetChild("hit").click() end
local function fixture(seed, callback)
    local root, map = mock(), Map.generate(data, seed or 42)
    return root, map, makeUI(root, map, callback or function(node) return Map.choose(map, node.id) end)
end
local function boxFor(root, map, id)
    -- Test-only identity lookup; no need to deep-copy all 43 nodes per lookup.
    for i, node in ipairs(map.nodes) do if node.id == id then return panel(root):GetChild("node" .. i), i end end
    error("missing real node")
end
local function clickNode(root, map, id)
    local box, i = boxFor(root, map, id)
    assert(box.visible, "selected node must be in viewport")
    assert(box:GetChild("hit").visible, "selected node must be clickable")
    return click(root, "node" .. i)
end
local function sameColor(a, b) return a.r == b.r and a.g == b.g and a.b == b.b and a.a == b.a end
local function visibleBounds(root, map)
    for _, node in ipairs(Map.view(map).nodes) do
        local box = boxFor(root, map, node.id)
        if box.visible then
            local radius = (box.w + Layout.glowPadding) * Layout.breathScale / 2
            assert(box.y - radius >= Layout.viewport.bottom and box.y + radius <= Layout.viewport.top)
            assert(math.abs(box.x) + radius <= Theme.canvas.base[1] / 2 - Theme.canvas.safe.x)
        end
    end
    for i = 1, Layout.maxEdges do
        local edge = panel(root):GetChild("edge" .. i)
        if edge.visible then
            local angle = edge.localRotationZ * math.pi / 180
            local halfH = (math.abs(edge.w * math.sin(angle)) + math.abs(edge.h * math.cos(angle))) / 2
            assert(edge.y - halfH >= Layout.viewport.bottom - .0001 and edge.y + halfH <= Layout.viewport.top + .0001)
        end
    end
end

test("initial controls show legal starts, shared icons and four states across all 15 floors", function()
    local root, map, ui = fixture()
    assert(ui.scroll == 0 and ui.navigationEnabled)
    assert(not panel(root):GetChild("previous").visible and panel(root):GetChild("next").visible)
    local seen, types = {}, {}
    for offset = 0, Layout.maxScroll + 60, 60 do
        assert(ui:setScroll(offset))
        for _, node in ipairs(Map.view(map).nodes) do
            local box = boxFor(root, map, node.id)
            if box.visible then
                seen[node.id], types[node.type] = true, true
                assert(box:GetChild(node.floor == 1 and "available" or "locked").visible)
                assert(box:GetChild("icon").image == Theme.icon.node[node.type])
                assert(box:GetChild("hit").visible == (node.floor == 1))
            end
        end
        visibleBounds(root, map)
    end
    for _, node in ipairs(Map.view(map).nodes) do assert(seen[node.id]) end
    for kind in pairs(Theme.icon.node) do assert(types[kind], "all seven real node types displayed") end
    local boss = boxFor(root, map, "f15_l2")
    assert(boss.w == Theme.layout.map.bossNode and boss:GetChild("icon").image == Theme.icon.node.boss)
end)

test("actual control clicks advance once, notify copied node and block reentrant/repeat choices", function()
    local received, callbackBlocked
    local root, map, ui
    root, map, ui = fixture(42, function(node)
        received = node
        local ok, reason = ui:choose(node.id)
        callbackBlocked = not ok and reason == "navigation_disabled"
        node.nextIds[1] = "tamper"
        return Map.choose(map, node.id)
    end)
    local first = Map.available(map)[1]
    assert(clickNode(root, map, first.id) and callbackBlocked)
    assert(map.floor == 1 and #map.path == 1 and not ui.navigationEnabled)
    assert(received.id == map.currentNodeId and map.nodes[1].nextIds[1] ~= "tamper")
    assert(boxFor(root, map, first.id):GetChild("current").visible)
    assert(not ui:choose(Map.available(map)[1].id) and map.floor == 1)
    ui:setNavigationEnabled(true)
    local nextNode = Map.available(map)[1]
    assert(clickNode(root, map, nextNode.id) and map.floor == 2)
    assert(boxFor(root, map, first.id):GetChild("visited").visible)
    assert(sameColor(panel(root):GetChild("edge1").imageColor, Theme.color.node.pathTaken))
end)

test("invalid, locked, backward, disconnected, culled and hidden clicks never mutate map", function()
    local callbacks = 0
    local root, map, ui
    root, map, ui = fixture(42, function(node) callbacks = callbacks + 1 return Map.choose(map, node.id) end)
    for _, id in ipairs({false, {}, "missing", "f5_l2"}) do
        assert(not ui:choose(id)); assert(map.floor == 0 and #map.path == 0)
    end
    assert(not ui:choose(nil))
    assert(not click(root, "node4")); assert(callbacks == 0)
    assert(not click(root, "node43")); assert(callbacks == 0)
    ui:setVisible(false)
    assert(not click(root, "node1")); click(root, "next"); assert(ui.scroll == 0)
    ui:setVisible(true); assert(clickNode(root, map, "f1_l1"))
    ui:setNavigationEnabled(true)
    local allowed = {}; for _, node in ipairs(Map.available(map)) do allowed[node.id] = true end
    for lane = 1, 3 do if not allowed["f2_l" .. lane] then assert(not ui:choose("f2_l" .. lane)) end end
    assert(not ui:choose("f1_l1")); assert(map.floor == 1 and callbacks == 1)
    for _, bad in ipairs({false, "2", 0/0, math.huge, -math.huge}) do assert(not ui:setScroll(bad)) end
    assert(ui:setScroll(-100) and ui.scroll == 0)
    assert(ui:setScroll(10000) and ui.scroll == Layout.maxScroll)
end)

test("scroll follows true 15-floor navigation and Boss arrival never reports victory", function()
    local callbacks = 0
    local root, map, ui
    root, map, ui = fixture(313, function(node) callbacks = callbacks + 1 return Map.choose(map, node.id) end)
    for floor = 1, 15 do
        ui:setNavigationEnabled(true)
        local selected = Map.available(map)[1]
        assert(clickNode(root, map, selected.id))
        assert(map.currentNodeId == selected.id and callbacks == floor)
        assert(boxFor(root, map, selected.id):GetChild("current").visible)
        visibleBounds(root, map)
    end
    ui:setNavigationEnabled(true)
    assert(not ui:choose("f15_l2") and callbacks == 15 and #map.path == 15)
    assert(panel(root):GetChild("notice").text == "已抵达首领 · 请完成首领战斗")
    assert(ui.scroll == Layout.maxScroll)
    assert(click(root, "previous") and ui.scroll < Layout.maxScroll)
    click(root, "focus"); assert(ui.scroll == Layout.maxScroll)
end)

test("restored maps start locked and reopening focuses actual current floor", function()
    local map = Map.generate(data, 1)
    for _ = 1, 7 do assert(Map.choose(map, Map.available(map)[1].id)) end
    local restored = assert(Map.restore(data, Map.snapshot(map)))
    local root = mock()
    local ui = makeUI(root, restored, function(node) return Map.choose(restored, node.id) end)
    assert(not ui.navigationEnabled and ui.scroll > 0)
    assert(boxFor(root, restored, restored.currentNodeId).visible)
    assert(not ui:choose(Map.available(restored)[1].id) and restored.floor == 7)
    ui:setScroll(0); ui:setVisible(false); ui:setVisible(true)
    assert(boxFor(root, restored, restored.currentNodeId).visible)
    ui:setNavigationEnabled(true)
    assert(clickNode(root, restored, Map.available(restored)[1].id) and restored.floor == 8)
end)

test("transaction rejection preserves map, lock and scroll, then accepts a later retry", function()
    local accepted, called = false, 0
    local root, map, ui
    root, map, ui = fixture(42, function(node)
        called = called + 1
        if not accepted then return false, "node_pending" end
        return Map.choose(map, node.id)
    end)
    local ok, reason = clickNode(root, map, "f1_l2")
    assert(not ok and reason == "node_pending" and called == 1)
    assert(map.floor == 0 and #map.path == 0 and ui.navigationEnabled and ui.scroll == 0)
    accepted = true
    assert(clickNode(root, map, "f1_l2") and map.floor == 1 and called == 2 and not ui.navigationEnabled)
    local otherRoot = mock()
    local incomplete = makeUI(otherRoot, Map.generate(data, 1), function() return true end)
    ok, reason = click(otherRoot, "node1")
    assert(not ok and reason == "selection_not_committed" and incomplete.navigationEnabled)
end)

test("callback errors release reentrancy guard and commits always lock even if callback rejects or throws", function()
    for _, failure in ipairs({"reject", "throw"}) do
        local root, map, ui
        root, map, ui = fixture(1, function(node)
            assert(Map.choose(map, node.id))
            if failure == "throw" then error("host failure") end
            return false, "host_rejected_after_commit"
        end)
        assert(not clickNode(root, map, "f1_l1") and map.floor == 1 and not ui.navigationEnabled and not ui.choosing)
        assert(not ui:choose(Map.available(map)[1].id) and #map.path == 1)
    end
    local root, map, ui = fixture(1, function() error("before commit") end)
    local ok, reason = clickNode(root, map, "f1_l1")
    assert(not ok and reason == "choice_callback_error" and ui.navigationEnabled and map.floor == 0 and not ui.choosing)
end)

test("phone, PC, console and ultrawide fit stage uniformly and fill background outside stage", function()
    local root, map, ui = fixture()
    for _, canvas in ipairs({{1280,720,1}, {1600,900,1.25}, {1920,1080,1.5}, {2340,1080,1.5}}) do
        assert(ui:resize(canvas[1], canvas[2]))
        assert(ui.stage.localScaleX == canvas[3] and ui.stage.localScaleY == canvas[3])
        assert(root:GetChild("mapBackdrop").w == canvas[1] and root:GetChild("mapBackdrop").h == canvas[2])
        for offset = 0, Layout.maxScroll + 120, 120 do ui:setScroll(offset); visibleBounds(root, map) end
    end
    for _, bad in ipairs({0, -1, 0/0, math.huge, "1280"}) do assert(not ui:resize(bad, 720)) end
end)

test("displayed edges match real topology and chosen path colours after scrolling", function()
    local root, map, ui = fixture()
    for _ = 1, 6 do assert(Map.choose(map, Map.available(map)[1].id)) end
    ui:focusCurrent()
    local current, index, taken = Map.view(map), {}, {}
    for _, node in ipairs(current.nodes) do index[node.id] = node end
    for i = 1, #current.path - 1 do taken[current.path[i] .. ":" .. current.path[i + 1]] = true end
    for offset = 0, Layout.maxScroll, 60 do
        ui:setScroll(offset)
        local n = 0
        for _, node in ipairs(current.nodes) do for _, id in ipairs(node.nextIds) do
            n = n + 1
            local edge = panel(root):GetChild("edge" .. n)
            local y1 = Layout.firstY + (node.floor - 1) * Theme.layout.map.floorGap - ui.scroll
            local y2 = Layout.firstY + (index[id].floor - 1) * Theme.layout.map.floorGap - ui.scroll
            local expected = y2 > Layout.viewport.bottom + Layout.lineWidth / 2 and y1 < Layout.viewport.top - Layout.lineWidth / 2
            assert(edge.visible == expected)
            if expected then assert(sameColor(edge.imageColor, taken[node.id .. ":" .. id] and Theme.color.node.pathTaken or Theme.color.node.path)) end
        end end
        for i = n + 1, Layout.maxEdges do assert(not panel(root):GetChild("edge" .. i).visible) end
    end
end)

test("reachable node breath is bounded, reduced motion stops it and stale view clicks revalidate", function()
    local root, map, ui = fixture()
    local node = Map.available(map)[1]
    local box = boxFor(root, map, node.id)
    assert(ui:update(Layout.breathSeconds / 2) and math.abs(box.localScaleX - Layout.breathScale) < .0001)
    ui:setReducedMotion(true); assert(box.localScaleX == 1)
    ui:setReducedMotion(false); assert(box.localScaleX > 1)
    assert(Map.choose(map, node.id))
    assert(not click(root, "node1") and #map.path == 1)
    ui:render()
    assert(box:GetChild("current").visible and not box:GetChild("hit").visible)
    for _, bad in ipairs({-1, 0/0, math.huge}) do assert(not ui:update(bad)) end
end)

