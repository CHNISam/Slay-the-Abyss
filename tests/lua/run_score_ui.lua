local F=dofile('tests/lua/support/game_ui_fixture.lua')
local Run=require('abyss_run')
local ui,root=F.fixture();assert(F.start(ui))
ui.run.phase='defeat';ui:refresh()
local result=assert(Run.resultScore(ui.run))
assert(F.resultText(root,'detail'):find('总分 '..result.total,1,true),'settlement must show computed total')
for _,key in ipairs({'floor','victories','time','deck'})do assert(F.statValue(root,key))end
local score=result.total;assert(Run.obtainRelic(ui.run,'Spirit Poop'))
assert(Run.resultScore(ui.run).total==score-1);ui:refresh()
assert(F.resultText(root,'detail'):find('总分 '..(score-1),1,true))
ui.run.phase='victory';ui:refresh();result=assert(Run.resultScore(ui.run))
assert(F.resultText(root,'detail'):find('总分 '..result.total,1,true))
ui.run.scoreStats=nil;ui:refresh();assert(not Run.resultScore(ui.run))
assert(F.resultText(root,'detail'):find('总分暂不可用',1,true))
print('PASS score real Host settlement, Spirit Poop, legacy unavailable; no official-client claim')
