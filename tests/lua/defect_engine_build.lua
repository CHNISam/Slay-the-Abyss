local n=0
local function eq(a,b)assert(a==b,tostring(a)..' ~= '..tostring(b))end
local function test(name,f)f();n=n+1;print('ok '..n..' '..name)end
local function setup(id,up,count,slots)
 local deck={};for i=1,(count or 1)do deck[i]={cardId=id,upgraded=up or false}end
 return C.new(data,{seed=42,orbSlots=slots==nil and 3 or slots,orbRandomSeed='17',deck=deck,enemies={'jaw_worm','jaw_worm'}})
end
local function uid(s,id)for _,c in ipairs(s.hand)do if c.cardId==id then return c.uid end end;error('missing '..id)end
local function play(s,id,target)assert(C.play(s,uid(s,id),target))end
local function ch(s,kind)assert(O.channel(s,kind,C))end
local function initialize(s)if not s.orbChannelCounts then E.initHistory(s)end end
local function loss(s,before)return before-s.enemies[1].hp-s.enemies[2].hp end
test('nineteen exact source definitions append independently and preserve input',function()
 eq(#data.cards.cards,#base.cards.cards+19);eq(#data.statuses.statuses,#base.statuses.statuses+1)
 local ids={};for _,c in ipairs(data.cards.cards)do ids[c.id]=c end
 eq(ids.claw.sourceId,'Gash');eq(ids.steam_barrier.sourceId,'Steam');eq(ids.multi_cast.sourceId,'Multi-Cast');eq(ids.lock_on.sourceId,'Lockon')
 for _,id in ipairs({'claw','stack','steam_barrier','streamline','aggregate','auto_shields','blizzard','chaos','chill','doom_and_gloom','lock_on','melter','rip_and_tear','skim','sunder','tempest','meteor_strike','multi_cast','thunder_strike'})do
  local c=assert(ids[id]);assert(c.sourceId and c.name and c.text and c.upgradeText and c.upgrade)
  for _,def in ipairs({c,c.upgrade})do for _,effect in ipairs(def.effects or {})do
   assert(E.ops[effect.op] or effect.op=='damage' or effect.op=='damageAll' or effect.op=='draw' or effect.op=='block' or effect.op=='channelOrb','unregistered external engine op')
  end end
 end
 eq(E.ops.engineRandomRounds,nil);eq(E.ops.engineChannelRounds,nil);eq(E.ops.engineEvokeRounds,nil);eq(E.ops.engineSunderRefund,nil)
 assert(not pcall(E.withCards,data))
end)
