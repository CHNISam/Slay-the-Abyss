local H=dofile('tests/lua/support/battle_gesture_fixture.lua')
local Theme=require('abyss_theme')
local passed,failed=0,0
local function test(name,fn)
 local ok,why=pcall(fn)
 if ok then passed=passed+1;print('PASS '..name) else failed=failed+1;print('FAIL '..name..': '..tostring(why)) end
end
for _,duration in ipairs({0.1,0.6}) do
 test('mobile invalid release cancels at '..duration,function()
  local h,u,p,e=H.setup({'defend'},nil,{touchScreen=function()return true end})
  e('card1','down',7);e('card1','drag',7,40,-150);h:update(duration)
  local line=p:GetChild('dragLayer'):GetChild('line')
  assert(p:GetChild('card1').y<line.y,'visible card center must stay below inactive release line')
  e('dragLayer','up',7,40,-150)
  assert(not u.carry and not u.selected and not u.gesture,'mobile invalid drag must return to Idle')
  assert(not p:GetChild('dragLayer').visible and h.run.combat.energy==3 and h.run.combat.player.block==0)
 end)
 test('mobile empty target release cancels at '..duration,function()
  local h,u,p,e=H.setup({'strike'},nil,{touchScreen=function()return true end})
  e('card1','down',7);e('card1','drag',7,-285,0);h:update(duration)
  e('dragLayer','up',7,-285,0)
  assert(not u.carry and not u.selected and not u.gesture and not p:GetChild('dragLayer').visible)
  assert(h.run.combat.energy==3 and #h.run.combat.hand==1)
  e('card1','endDrag',7,-285,0);e('card1','click',7)
  assert(not u.selected and h.run.combat.energy==3,'late events cannot revive cancelled drag')
 end)
end
test('mobile legal release submits once and tap fallback remains available',function()
 local h,u,p,e,tap=H.setup({'defend','defend'},nil,{touchScreen=function()return true end})
 e('card1','down',7);e('card1','drag',7,40,0);e('dragLayer','up',7,40,0)
 e('card1','endDrag',7,40,0);e('card1','click',7)
 assert(h.run.combat.energy==2 and h.run.combat.player.block==5 and #h.run.combat.hand==1)
end)
test('desktop empty target release retains established aim',function()
 local h,u,p,e=H.setup({'strike'})
 e('card1','down',7);e('card1','drag',7,-285,0);e('dragLayer','up',7,-285,0)
 assert(u.carry and u.selected and u.carry.aiming and h.run.combat.energy==3)
end)
test('mobile pickup keeps grab offset instead of snapping finger-above',function()
 local h,u,p,e=H.setup({'defend'},nil,{touchScreen=function()return true end})
 local card=p:GetChild('card1');local x0,y0=card.x,card.y
 e('card1','down',7);e('card1','drag',7,x0,y0+10)
 assert(u.gesture and u.gesture.moving,'threshold crossed')
 assert(math.abs(card.y-y0)<60,'first frame after threshold must stay near grab, got dy='..(card.y-y0))
 e('card1','drag',7,x0,y0+200)
 assert(math.abs(card.y-(y0+200)-270*u.gesture.sourceScale)<1,'past 80px the finger-above pose is reached')
end)
print('MOBILE_CARD_RELEASE '..passed..' passed; '..failed..' failed')
assert(failed==0,'mobile release failures')
