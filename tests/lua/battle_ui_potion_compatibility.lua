local testStart=dofile('tests/lua/support/game_ui_fixture.lua').start
local H = dofile("tests/lua/support/potion_gesture_fixture.lua")
local F, Run, fixture = H.F, H.Run, H.setup
local test, finish = H.suite("LUA_POTION_COMPATIBILITY")

test("fresh paired potion Down Up Click consumes exactly once",function()
    local h,u,p,e,t,d,deck,r,emit,tap=fixture()
    local b=h.run.combat
    tap(7);d();emit("potion1","click",7)
    assert(b.energy==5 and Run.potionCount(h.run)==0)
end)
test("callback-only host remains compatible",function()
    local h,u,p,e,t,d=fixture()
    p:GetChild("potion1").click();d()
    assert(h.run.combat.energy==5 and Run.potionCount(h.run)==0)
end)
test("click-only potion remains compatible after real paired card input",function()
    local h,u,p,e,t,d=fixture()
    t("card1",8);t("playArea",8);d()
    assert(h.run.combat.energy==2 and h.run.combat.player.block==5)
    p:GetChild("potion1").click();d()
    assert(h.run.combat.energy==4 and Run.potionCount(h.run)==0)
end)
test("fresh paired potion after deck close remains valid",function()
    local h,u,p,e,t,d,deck,r,emit,tap=fixture()
    deck();tap(8);d()
    assert(h.run.combat.energy==5 and Run.potionCount(h.run)==0)
end)
test("stale callback during card animation remains rejected",function()
    local h,u,p,e,t,d,deck,r,emit=fixture()
    emit("potion1","down",7);t("card1",8);t("playArea",8)
    assert(u.busy);emit("potion1","up",7);emit("potion1","click",7)
    assert(h.run.potions[1]=="energy_potion" and h.run.combat.energy==2)
end)
test("metadata-free Down Up Click and same-ID fresh gesture survive resize",function()
    local h,u,p,e,t,d,deck,r,emit,tap=fixture()
    emit("potion1","down",nil); h:resize(1600,900)
    emit("potion1","up",nil); emit("potion1","click",nil)
    assert(h.run.combat.energy==3)
    tap(nil); d(); assert(h.run.combat.energy==5)
end)
test("host with no pointer enums retains click-only potions",function()
    local h,r=F.fixture(); assert(testStart(h)); assert(Run.startCombat(h.run,"cultist_solo"))
    assert(Run.obtainPotion(h.run,"energy_potion")); h:refresh()
    r:GetChild("battlePanel"):GetChild("potion1").click()
    assert(h.run.potions[1]==nil and h.run.combat.energy==5)
end)
test("sparse targeted potion follows fresh target selection without moving slots",function()
    local h,u,p,e,t,d,deck,r,emit,tap=fixture({"defend"},{"cultist","jaw_worm"})
    assert(Run.obtainPotion(h.run,"fire_potion")); h:refresh()
    tap(7); d()
    assert(h.run.potions[1]==nil and h.run.potions[2]=="fire_potion")
    local b=h.run.combat; local hp1,hp2=b.enemies[1].hp,b.enemies[2].hp
    emit("enemy2","down",8); emit("enemy2","click",8)
    assert(u.target==2)
    tap(9,2); d()
    assert(h.run.potions[2]=="fire_potion")
    emit("enemy2","down",10); emit("enemy2","click",10); d()
    assert(h.run.potions[2]==nil and b.enemies[1].hp==hp1 and b.enemies[2].hp==hp2-20)
end)
test("invalid focus does not submit a potion and fresh enemy confirmation commits once",function()
    local h,u,p,e,t,d,deck,r,emit,tap=fixture({"defend"},{"cultist","jaw_worm"})
    assert(Run.obtainPotion(h.run,"fire_potion")); h:refresh()
    u.target=99 -- default focus is never used as the potion's confirmation
    tap(7,2); assert(h.run.potions[2]=="fire_potion" and not u.busy)
    assert(not Run.usePotion(h.run,2,99))
    emit("potion2","click",7); assert(h.run.potions[2]=="fire_potion")
    emit("enemy2","down",8); emit("enemy2","click",8)
    d(); assert(h.run.potions[2]==nil)
end)
test("harmless redraws preserve held and released potion ownership",function()
    local h,u,p,e,t,d,deck,r,emit=fixture()
    local inventory=h.run.potions
    emit("potion1","down",7); h:refresh(); u:render()
    emit("potion1","up",7); h:refresh(); u:render()
    assert(h.run.potions==inventory)
    emit("potion1","click",7); d(); assert(h.run.combat.energy==5)
end)
test("real potion transaction replaces inventory identity but acquisition preserves it",function()
    local h,u,p,e,t,d,deck,r,emit=fixture()
    local inventory=h.run.potions
    assert(Run.obtainPotion(h.run,"block_potion")); assert(h.run.potions==inventory)
    assert(Run.usePotion(h.run,1)); assert(h.run.potions~=inventory)
    local committed=h.run.potions
    assert(Run.obtainPotion(h.run,"energy_potion")); assert(h.run.potions==committed)
end)
finish()
